#!/usr/bin/env node
/**
 * Deterministic onto service-worker generator.
 * Pure Node (crypto/fs/path only). Writes public/sw.js.
 *
 *   node scripts/pwa/build-sw.mjs [--dist dist]
 *
 * Release builds MUST pass --dist (npm run build / build:release do): the hash
 * then covers dist/index.html + every dist/_expo/static/** file, so each deploy
 * gets a new cache name, and the worker is written ONLY to <dist>/sw.js
 * (public/sw.js stays the committed no-dist placeholder).
 * Without dist (dev/test) the hash falls back to generator + precache only.
 *
 * Strategies baked into the worker:
 *   Cache-First  — app shell (HTML, /_expo/static/*, icons, manifest)
 *   Network-Only — Supabase /auth/v1, /rest/v1, /realtime/v1 (never cache; RLS)
 *   Catalog      — persisted by the app via lib/storage.ts key onto.catalog.v1;
 *                  this worker does not cache API catalog responses.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '../..');
const OUT = path.join(ROOT, 'public', 'sw.js');

/** Minimal shell precache. Icons land with W1; addAll skips missing at runtime. */
export const PRECACHE_URLS = Object.freeze([
  '/',
  '/index.html',
  '/manifest.json',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
  '/icons/icon-maskable-512.png',
]);

/** Stable SHA-256 prefix over ordered input strings. */
export function computeBuildHash(parts) {
  const h = crypto.createHash('sha256');
  for (const part of parts) h.update(String(part));
  h.update('\n');
  return h.digest('hex').slice(0, 16);
}

/**
 * True when the response must never enter a Cache Storage bucket.
 * Fail closed on unparseable URLs.
 */
export function isNetworkOnlyUrl(urlString, base = 'https://onto.events') {
  let u;
  try {
    u = new URL(urlString, base);
  } catch {
    return true;
  }
  const host = u.hostname.toLowerCase();
  const p = u.pathname;
  if (p.includes('/auth/v1') || p.startsWith('/auth/v1')) return true;
  if (p.includes('/rest/v1') || p.startsWith('/rest/v1')) return true;
  if (p.includes('/realtime/v1') || p.startsWith('/realtime/v1')) return true;
  if (host.endsWith('supabase.co') || host.endsWith('supabase.in')) {
    if (
      p.startsWith('/auth/') ||
      p.startsWith('/rest/') ||
      p.startsWith('/realtime/') ||
      p.startsWith('/functions/')
    ) {
      return true;
    }
  }
  return false;
}

/** Sorted dist-relative paths that define a deploy: index.html + _expo/static/**. */
export function listDistShell(distDir) {
  const out = [];
  if (fs.existsSync(path.join(distDir, 'index.html'))) out.push('index.html');
  const walk = (rel) => {
    const abs = path.join(distDir, rel);
    if (!fs.existsSync(abs)) return;
    for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
      const r = `${rel}/${e.name}`;
      if (e.isDirectory()) walk(r);
      else if (e.isFile()) out.push(r);
    }
  };
  walk('_expo/static');
  walk('assets/pkg');
  return out.sort();
}

/** Hash inputs for a dist tree: path + sha256(content) per file, stable order. */
export function hashDistTree(distDir) {
  return listDistShell(distDir).map(
    (rel) => `${rel}:${crypto.createHash('sha256').update(fs.readFileSync(path.join(distDir, rel))).digest('hex')}\n`,
  );
}

/** Shell / static asset paths eligible for Cache-First. Same-origin only. */
export function isShellAssetUrl(urlString, base = 'https://onto.events') {
  let u;
  try {
    u = new URL(urlString, base);
  } catch {
    return false;
  }
  if (u.origin !== new URL(base).origin) return false;
  const p = u.pathname;
  if (p === '/' || p === '/index.html') return true;
  if (p === '/manifest.json' || p === '/manifest.webmanifest') return true;
  if (p.startsWith('/_expo/static/')) return true;
  if (p.startsWith('/icons/')) return true;
  if (p.startsWith('/assets/pkg/')) return true;
  if (p === '/favicon.ico' || p === '/og-image.png') return true;
  return false;
}

export function renderServiceWorker({ buildHash, precache }) {
  const precacheJson = JSON.stringify([...precache], null, 0);
  const shellCache = `onto-shell-${buildHash}`;
  return `/* onto service worker — generated by scripts/pwa/build-sw.mjs; do not edit */
/* BUILD_HASH=${buildHash} */
/* Cache-Control for this file is owned by public/_headers (W1): no-cache */
/* eslint-disable no-restricted-globals */
'use strict';

var BUILD_HASH = ${JSON.stringify(buildHash)};
var SHELL_CACHE = ${JSON.stringify(shellCache)};
var PRECACHE = ${precacheJson};

function isNetworkOnly(url) {
  try {
    var u = new URL(url);
    var host = u.hostname.toLowerCase();
    var p = u.pathname;
    if (p.indexOf('/auth/v1') !== -1 || p.indexOf('/rest/v1') !== -1 || p.indexOf('/realtime/v1') !== -1) {
      return true;
    }
    if (host.indexOf('supabase.co') !== -1 || host.indexOf('supabase.in') !== -1) {
      if (
        p.indexOf('/auth/') === 0 ||
        p.indexOf('/rest/') === 0 ||
        p.indexOf('/realtime/') === 0 ||
        p.indexOf('/functions/') === 0
      ) {
        return true;
      }
    }
    return false;
  } catch (e) {
    return true;
  }
}

function isShellAsset(url) {
  try {
    var u = new URL(url);
    if (u.origin !== self.location.origin) return false;
    var p = u.pathname;
    if (p === '/' || p === '/index.html') return true;
    if (p === '/manifest.json' || p === '/manifest.webmanifest') return true;
    if (p.indexOf('/_expo/static/') === 0) return true;
    if (p.indexOf('/icons/') === 0) return true;
    if (p.indexOf('/assets/pkg/') === 0) return true;
    if (p === '/favicon.ico' || p === '/og-image.png') return true;
    return false;
  } catch (e) {
    return false;
  }
}

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(SHELL_CACHE).then(function (cache) {
      /* Shell entrypoints are critical: a miss fails install (old SW keeps serving). */
      return Promise.all([cache.add('/'), cache.add('/index.html')]).then(function () {
        return Promise.all(
          PRECACHE.filter(function (url) {
            return url !== '/' && url !== '/index.html';
          }).map(function (url) {
            return cache.add(url).catch(function () {
              /* optional asset (icons) may be missing — skip */
            });
          }),
        );
      });
    }).then(function () {
      /* Only after critical precache: new build takes over immediately (small PWA, no update UX). */
      return self.skipWaiting();
    }),
  );
});

/* Shell generations: meta records {cur, prev}. Activate keeps SHELL_CACHE plus
   exactly one previous shell so a tab still on the old build can load its old
   hashed chunks during the update window; every older onto-shell-* is deleted. */
var META_CACHE = 'onto-sw-meta';
var META_KEY = '/__onto-sw/shells';

function readShells() {
  return caches.open(META_CACHE).then(function (c) {
    return c.match(META_KEY);
  }).then(function (r) {
    return r ? r.text().then(JSON.parse) : null;
  }).then(function (m) {
    return m && typeof m.cur === 'string' ? m : null;
  }).catch(function () {
    return null;
  });
}

function isHashedAsset(url) {
  try {
    var u = new URL(url);
    if (u.origin !== self.location.origin) return false;
    return u.pathname.indexOf('/_expo/static/') === 0 || u.pathname.indexOf('/assets/pkg/') === 0;
  } catch (e) {
    return false;
  }
}

self.addEventListener('activate', function (event) {
  event.waitUntil(
    Promise.all([caches.keys(), readShells()]).then(function (r) {
      var keys = r[0];
      var meta = r[1];
      var older = keys.filter(function (k) {
        return k.indexOf('onto-shell-') === 0 && k !== SHELL_CACHE;
      });
      /* No meta = first run after a worker that kept one shell: that one is prev.
         Relies on caches.keys() returning creation order, so the last key is newest. */
      var prev = meta ? (meta.cur !== SHELL_CACHE ? meta.cur : meta.prev) : older[older.length - 1];
      if (older.indexOf(prev) === -1) prev = null;
      /* Meta first: a kill mid-activate then leaves only extra caches, never a meta naming a deleted one. */
      return caches.open(META_CACHE).then(function (c) {
        return c.put(META_KEY, new Response(JSON.stringify({ cur: SHELL_CACHE, prev: prev })));
      }).then(function () {
        return Promise.all(
          older.map(function (key) {
            return key === prev ? undefined : caches.delete(key);
          }),
        );
      });
    }).then(function () {
      return self.clients.claim();
    }),
  );
});

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;

  var url = req.url;
  if (isNetworkOnly(url)) {
    event.respondWith(fetch(req));
    return;
  }

  /* Never cache the worker script itself — always network so updates land. */
  try {
    var path = new URL(url).pathname;
    if (path === '/sw.js' || path === '/service-worker.js') {
      event.respondWith(fetch(req));
      return;
    }
  } catch (e) {
    event.respondWith(fetch(req));
    return;
  }

  if (req.mode === 'navigate') {
    /* SPA navigations: network first (fresh deploys win); offline falls back to
       cached req (ignoreSearch so /?source=pwa hits /), then /index.html, then /. No cache writes. */
    event.respondWith(
      fetch(req).catch(function () {
        return caches.open(SHELL_CACHE).then(function (cache) {
          return cache.match(req, { ignoreSearch: true }).then(function (hit) {
            return hit || cache.match('/index.html', { ignoreSearch: true });
          }).then(function (r) {
            return r || cache.match('/', { ignoreSearch: true });
          }).then(function (r) {
            return r || Response.error();
          });
        });
      }),
    );
    return;
  }

  if (isShellAsset(url)) {
    event.respondWith(
      caches.open(SHELL_CACHE).then(function (cache) {
        return cache.match(req, { ignoreSearch: true }).then(function (hit) {
          if (hit) return hit;
          /* Old tab, old hashed chunk: try the previous shell before network. */
          return (isHashedAsset(url) ? readShells() : Promise.resolve(null)).then(function (m) {
            return m && m.prev ? caches.match(req, { cacheName: m.prev, ignoreSearch: true }) : undefined;
          });
        }).then(function (hit) {
          if (hit) return hit;
          return fetch(req).then(function (res) {
            if (res && res.ok) {
              cache.put(req, res.clone());
            }
            return res;
          });
        });
      }),
    );
    return;
  }

  /* Default: network, no Cache Storage write (avoids poisoning API/catalog). */
  event.respondWith(fetch(req));
});
`;
}

const TEXT_EXT = /\.(html|js|css|json|map|txt|webmanifest)$/;

/**
 * Pages uploads skip every node_modules path segment, so any such file or URL
 * in dist is an asset that will 404 (HTML shell) in production. Returns the
 * offending dist-relative paths; empty means clean.
 */
export function findNodeModulesLeaks(distDir) {
  const bad = [];
  const walk = (rel) => {
    for (const e of fs.readdirSync(path.join(distDir, rel), { withFileTypes: true })) {
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.name === 'node_modules') { bad.push(`${r}/ (path)`); continue; }
      if (e.isDirectory()) walk(r);
      else if (TEXT_EXT.test(e.name) && /\/?assets\/node_modules\//.test(fs.readFileSync(path.join(distDir, r), 'utf8'))) {
        bad.push(`${r} (references assets/node_modules/)`);
      }
    }
  };
  walk('');
  return bad;
}

export function build(root = ROOT, distDir = null) {
  const out = path.join(root, 'public', 'sw.js');
  const dist = distDir && fs.existsSync(path.join(distDir, 'index.html')) ? distDir : null;
  const staticUrls = dist
    ? listDistShell(dist).filter((r) => r !== 'index.html').map((r) => `/${r}`)
    : [];
  const precache = [...PRECACHE_URLS, ...staticUrls];
  const hash = computeBuildHash([
    'onto-sw-v2',
    ...precache,
    ...(dist ? hashDistTree(dist) : []),
    // Salt with generator identity so logic edits bust the cache name.
    renderServiceWorker({ buildHash: '0', precache: PRECACHE_URLS }).replace(
      /BUILD_HASH=0/g,
      'BUILD_HASH=',
    ),
  ]);
  const source = renderServiceWorker({ buildHash: hash, precache });
  // A dist build writes only <dist>/sw.js: its precache is one export's file
  // list and must never be committed via public/sw.js.
  const target = dist ? path.join(dist, 'sw.js') : out;
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, source, 'utf8');
  return { out: target, buildHash: hash, bytes: Buffer.byteLength(source), dist };
}

const isMain =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const i = process.argv.indexOf('--dist');
  const distArg = i !== -1 ? process.argv[i + 1] : null;
  const distDir = i !== -1 ? path.resolve(ROOT, distArg) : null;
  if (distDir && !fs.existsSync(path.join(distDir, 'index.html'))) {
    process.stderr.write(`build-sw: --dist ${distArg} has no index.html; run expo export first\n`);
    process.exit(1);
  }
  const leaks = distDir ? findNodeModulesLeaks(distDir) : [];
  if (leaks.length) {
    process.stderr.write(`build-sw: dist ships node_modules asset paths (Pages drops them):\n  ${leaks.join('\n  ')}\n`);
    process.exit(1);
  }
  const result = build(ROOT, distDir);
  // Status on stderr so release-contract fixtures that JSON-parse the
  // expo-export stdout stay pure. Real builds still see the line.
  process.stderr.write(
    `wrote ${path.relative(ROOT, result.out)} hash=${result.buildHash} bytes=${result.bytes}\n`,
  );
}
